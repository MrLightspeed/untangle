import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import {
  checkSkillPayload,
  expectedSkillFiles,
} from "../scripts/check-skill-payload.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fixtureLifecycle = path.resolve(root, "tests", "fixture_lifecycle.py");

function withFixture(run) {
  const fixture = execFileSync("python", [fixtureLifecycle, "create"], {
    encoding: "utf8",
    windowsHide: true,
    timeout: 10000,
  }).trim();
  try {
    for (const file of expectedSkillFiles) {
      const source = path.join(root, "skills", "untangle", file);
      const target = path.join(fixture, "skills", "untangle", file);
      mkdirSync(path.dirname(target), { recursive: true });
      copyFileSync(source, target);
    }
    run(fixture);
  } finally {
    execFileSync("python", [fixtureLifecycle, "clean", fixture], {
      windowsHide: true,
      timeout: 10000,
    });
  }
}

function git(fixture, args) {
  const env = { ...process.env };
  for (const name of [
    "GIT_DIR",
    "GIT_WORK_TREE",
    "GIT_COMMON_DIR",
    "GIT_INDEX_FILE",
    "GIT_OBJECT_DIRECTORY",
    "GIT_ALTERNATE_OBJECT_DIRECTORIES",
  ]) {
    delete env[name];
  }
  return execFileSync("git", args, {
    cwd: fixture,
    encoding: "utf8",
    env,
    windowsHide: true,
    timeout: 10000,
  }).trim();
}

test("checks a clean skill in a source snapshot without Git", () => {
  withFixture((fixture) => {
    assert.doesNotThrow(() => checkSkillPayload(fixture));
  });
});

test("rejects archives, development files, and missing required files", () => {
  withFixture((fixture) => {
    const skill = path.join(fixture, "skills", "untangle");
    const archive = path.join(skill, "bundle.zip");
    writeFileSync(archive, "archive");
    assert.throws(() => checkSkillPayload(fixture), /bundle\.zip/);
    rmSync(archive);

    const helper = path.join(skill, "scripts", "tests", "helper.py");
    mkdirSync(path.dirname(helper));
    writeFileSync(helper, "helper");
    assert.throws(
      () => checkSkillPayload(fixture),
      /scripts\/tests\/helper\.py/,
    );
    rmSync(helper);

    rmSync(path.join(skill, "LICENSE.txt"));
    assert.throws(
      () => checkSkillPayload(fixture),
      /Missing files.*LICENSE\.txt/,
    );
  });
});

// Allow for native Git startup and filesystem work on slower machines.
test(
  "ignores local bytecode but rejects bytecode tracked by Git",
  { timeout: 45000 },
  () => {
    withFixture((fixture) => {
      writeFileSync(path.join(fixture, ".gitignore"), "__pycache__/\n");
      git(fixture, ["init", "-q", "--initial-branch=main"]);
      const topLevel = git(fixture, ["rev-parse", "--show-toplevel"]);
      assert.equal(path.resolve(topLevel), path.resolve(fixture));
      git(fixture, [
        "-c",
        "core.autocrlf=false",
        "add",
        "--",
        "skills/untangle",
      ]);

      const cache = path.join(
        fixture,
        "skills",
        "untangle",
        "scripts",
        "__pycache__",
        "render_map.pyc",
      );
      mkdirSync(path.dirname(cache));
      writeFileSync(cache, "generated bytecode");
      assert.doesNotThrow(() => checkSkillPayload(fixture));

      git(fixture, [
        "add",
        "-f",
        "--",
        "skills/untangle/scripts/__pycache__/render_map.pyc",
      ]);
      assert.throws(
        () => checkSkillPayload(fixture),
        /Git index and untracked files.*scripts\/__pycache__\/render_map\.pyc/,
      );
    });
  },
);
